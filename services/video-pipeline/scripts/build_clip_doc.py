"""Build docs/clip_violations.md: every training clip, the team's description, and the rules and norms
(verbatim, from rules_kb.json) that the team's analysis links to it. Nothing in the doc is typed by hand.

    PYTHONPATH=src .venv/bin/python scripts/build_clip_doc.py --labels <open_labels.xlsx> [--scan runs/scan]
"""

import argparse
import json
import re
from pathlib import Path

from kassa_pipeline.cli import load_labels

DOCS = Path(__file__).resolve().parents[3] / "docs"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--labels", required=True)
    ap.add_argument("--scan", default="runs/scan", help="kassa scan results, for the detection column")
    a = ap.parse_args()

    kb = json.loads((DOCS / "rules_kb.json").read_text("utf8"))
    notes = json.loads((DOCS / "clip_notes.json").read_text("utf8"))
    labels = load_labels(Path(a.labels))
    docs, rules = kb["documents"], {r["id"]: r for r in kb["rules"]}
    by_clip: dict[int, list[str]] = {}
    for r in kb["rules"]:
        for c in r.get("observed_in", {}):
            by_clip.setdefault(int(re.search(r"(\d+)$", c).group(1)), []).append(r["id"])

    found: dict[int, list[str]] = {}
    for p in Path(a.scan).glob("*.json"):
        r = json.loads(p.read_text())
        if "findings" in r:
            n = int(re.search(r"(\d+)$", p.stem).group(1))
            found[n] = sorted({f["rule"] for f in r["findings"] if f["confidence"] >= 0.5})

    ACT = {"NBRK-231": "НБРК № 231", "NBRK-14": "НБРК № 14", "AFR-53": "АРРФР № 53"}

    def act(rule_id: str) -> str:
        r = rules[rule_id]
        return f"{ACT.get(r['doc'], r['doc'])}, {r['point']}"

    def weak(rule_id: str) -> bool:
        s = rules[rule_id]["strength"].lower()
        return s.startswith(("indirect", "hypothesis", "partly")) or "weak" in s

    L = ["# Training clips: violations, rules and norms", "",
         "Generated by `services/video-pipeline/scripts/build_clip_doc.py` from `docs/clip_notes.json` (the team's description of each clip), "
         "`docs/rules_kb.json` (rules, verbatim norm text and the clips linked to each rule) and `open_labels.xlsx` (labeled second). "
         "Edit those files, not this one.", "",
         "Acts (all read on adilet.zan.kz):", ""]
    for d in docs.values():
        L.append(f"- {d['short_ru']}: {d['url']}")
    L += ["", "Rules marked † are an indirect or hypothetical fit: the description must stay at the level of what is visible.", ""]

    L += ["## Violation clips", "", "| Clip | Second | What happens (team) | Rules | Norm | Scan finds |", "|---|---|---|---|---|---|"]
    ctrl = []
    for n in sorted(labels):
        viol, sec = labels[n]
        note = notes["clips"].get(str(n)) or (f"Same file as X-{notes['duplicates'][str(n)]}." if str(n) in notes.get("duplicates", {}) else "—")
        if not viol:
            ctrl.append((n, note))
            continue
        rs = by_clip.get(n, [])
        rule_txt = "<br>".join(f"{r}{' †' if weak(r) else ''}" for r in rs) or "no norm found"
        norm_txt = "<br>".join(act(r) for r in rs) or "—"
        hit = found.get(n)
        scan = "—" if hit is None else ("✓ " if set(hit) & set(rs) else "✗ ") + (", ".join(hit) or "nothing")
        L.append(f"| X-{n} | {'' if sec is None else f'{sec:.0f}'} | {note} | {rule_txt} | {norm_txt} | {scan} |")

    L += ["", "## Control clips (no violation)", "", "| Clip | Team note | Scan finds |", "|---|---|---|"]
    for n, note in ctrl:
        hit = found.get(n)
        L.append(f"| X-{n} | {note} | {'—' if hit is None else (', '.join(hit) or 'nothing ✓') + (' ✗' if hit else '')} |")

    L += ["", "## Reference sequences (team)", "", f"- **Операция:** {notes['reference']['transaction']}",
          f"- **Уход с рабочего места:** {notes['reference']['leaving']}", ""]

    L += ["## Rules and norms", ""]
    for r in kb["rules"]:
        d = docs[r["doc"]]
        clips = ", ".join(r.get("observed_in", {})) or "no training clip"
        L += [f"### {r['id']}{' †' if weak(r['id']) else ''}: {d['short_ru']}, {r['point']}", "",
              f"> {r['quote_ru']}", ""]
        if r.get("quote2_ru"):
            L += [f"> {r['quote2_ru']}", ""]
        L += [f"- What it means on video: {r['visual_check']}", f"- Fit: {r['strength']}"]
        if r.get("caveat"):
            L.append(f"- Caveat: {r['caveat']}")
        L += [f"- Clips: {clips}", f"- Source: {d['url']}", ""]

    L += ["## Observations with no norm found", ""]
    for k, v in kb["_meta"].get("unmapped_observations", {}).items():
        L.append(f"- **{k}**: {v}")
    out = DOCS / "clip_violations.md"
    out.write_text("\n".join(L) + "\n", "utf8")
    print(out)


if __name__ == "__main__":
    main()
